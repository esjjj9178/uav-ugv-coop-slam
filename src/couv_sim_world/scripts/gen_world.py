import layout as L  # noqa: E402

PKG_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
README_BEGIN = "<!-- LAYOUT_TABLE_BEGIN (generated by scripts/gen_world.py) -->"
README_END = "<!-- LAYOUT_TABLE_END -->"
ZONE_TEXT = {
    "structure": "structure",
    "under": "under roof (UGV only)",
    "roof": "on roof (UAV only)",
    "shared": "shared landmark (both)",
    "marker": "floor marker (no collision)",
}


def f(v):
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def vec(*vals):
    return " ".join(f(v) for v in vals)


# ---------------------------------------------------------------- geometry helpers
def geometry_xml(part):
    if part["shape"] == "box":
        return f"<box><size>{vec(*part['size'])}</size></box>"
    r, h = part["size"]
    return f"<cylinder><radius>{f(r)}</radius><length>{f(h)}</length></cylinder>"


def part_extent(model, part):
    """World-frame axis-aligned extent (xmin, xmax, ymin, ymax, zmin, zmax). Yaw is ignored (all 0)."""
    mx, my, mz, _ = model["pose"]
    px, py, pz = part["pos"]
    cx, cy, cz = mx + px, my + py, mz + pz
    if part["shape"] == "box":
        sx, sy, sz = part["size"]
    else:
        r, sz = part["size"]
        sx = sy = 2 * r
    return (cx - sx / 2, cx + sx / 2, cy - sy / 2, cy + sy / 2, cz - sz / 2, cz + sz / 2)


def model_extent(model):
    ex = np.array([part_extent(model, p) for p in model["parts"]])
    return (ex[:, 0].min(), ex[:, 1].max(), ex[:, 2].min(), ex[:, 3].max(), ex[:, 4].min(), ex[:, 5].max())


def texture_mean(model, tex):
    path = os.path.join(PKG_DIR, "models", model["name"], "materials", "textures", f"{tex}.png")
    if os.path.exists(path):
        img = Image.open(path).convert("RGB")
        img.thumbnail((64, 64))
        return np.asarray(img, np.float32).reshape(-1, 3).mean(0) / 255.0
    return np.mean(np.asarray(model["textures"][tex]["colors"], np.float32), 0) / 255.0


# ---------------------------------------------------------------- SDF writers
def material_xml(model, tex, indent):
    # gz multiplies <diffuse> with the albedo map, so keep the tint pale (mostly white)
    # while still carrying the texture's hue as a fallback if the PNG fails to load.
    mean = texture_mean(model, tex)
    tint = 0.75 + 0.25 * mean
    amb = 0.6 * tint
    uri = f"model://{model['name']}/materials/textures/{tex}.png"
    p = " " * indent
    return (f"{p}<material>\n"
            f"{p}  <ambient>{vec(*amb, 1)}</ambient>\n"
            f"{p}  <diffuse>{vec(*tint, 1)}</diffuse>\n"
            f"{p}  <specular>0.05 0.05 0.05 1</specular>\n"
            f"{p}  <pbr>\n"
            f"{p}    <metal>\n"
            f"{p}      <albedo_map>{uri}</albedo_map>\n"
            f"{p}      <roughness>0.9</roughness>\n"
            f"{p}      <metalness>0.0</metalness>\n"
            f"{p}    </metal>\n"
            f"{p}  </pbr>\n"
            f"{p}</material>\n")


def model_sdf(model):
    out = ['<?xml version="1.0"?>', '<sdf version="1.9">', f'  <model name="{model["name"]}">',
           "    <static>true</static>", '    <link name="link">']
    if "ground_plane" in model:
        gx, gy = model["ground_plane"]
        out += ['      <collision name="ground_collision">',
                f"        <geometry><plane><normal>0 0 1</normal><size>{vec(gx, gy)}</size></plane></geometry>",
                "        <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface>",
                "      </collision>"]
    for part in model["parts"]:
        pose = f"<pose>{vec(*part['pos'], 0, 0, 0)}</pose>"
        geom = f"<geometry>{geometry_xml(part)}</geometry>"
        if part["collision"]:
            out += [f'      <collision name="{part["name"]}_collision">', f"        {pose}", f"        {geom}",
                    "      </collision>"]
        out += [f'      <visual name="{part["name"]}_visual">', f"        {pose}", f"        {geom}",
                "        <cast_shadows>true</cast_shadows>"]
        out.append(material_xml(model, part["texture"], 8).rstrip("\n"))
        out.append("      </visual>")
    out += ["    </link>", "  </model>", "</sdf>", ""]
    return "\n".join(out)


def model_config(model):
    return f"""<?xml version="1.0"?>
<model>
  <name>{model['name']}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author><name>couv_sim_world generator</name></author>
  <description>{model['label']} ({ZONE_TEXT[model['zone']]}). Generated from scripts/layout.py.</description>
</model>
"""


