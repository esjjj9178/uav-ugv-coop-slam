# ---------------------------------------------------------------- sanity checks
def seg_point_dist(a, b, p):
    a, b, p = (np.asarray(v, float) for v in (a, b, p))
    t = np.clip(np.dot(p - a, b - a) / max(np.dot(b - a, b - a), 1e-9), 0, 1)
    return float(np.linalg.norm(a + t * (b - a) - p))


def route_clearance(model):
    """Minimum distance from the UGV route polyline to the model footprint."""
    best = math.inf
    for part in model["parts"]:
        x0, x1, y0, y1, z0, _ = part_extent(model, part)
        if z0 >= 1.0:  # overhead (roof slab) - the UGV drives underneath
            continue
        for a, b in zip(L.UGV_ROUTE[:-1], L.UGV_ROUTE[1:]):
            if part["shape"] == "cylinder":
                d = seg_point_dist(a, b, ((x0 + x1) / 2, (y0 + y1) / 2)) - (x1 - x0) / 2
            else:  # sample the segment against the rectangle
                d = min(math.hypot(max(x0 - x, 0, x - x1), max(y0 - y, 0, y - y1))
                        for x, y in (np.asarray(a) + t * (np.asarray(b) - np.asarray(a)) for t in np.linspace(0, 1, 200)))
            best = min(best, d)
    return best


def checks():
    msgs = []
    roof_max = max(model_extent(m)[5] for m in L.MODELS if m["zone"] == "roof")
    msgs.append(f"highest rooftop object z = {roof_max:.2f} m, drone altitude {L.DRONE_ALTITUDE} m "
                f"-> clearance {L.DRONE_ALTITUDE - roof_max:.2f} m")
    assert roof_max < L.DRONE_ALTITUDE, "rooftop object reaches the drone altitude"
    for m in L.MODELS:
        if m["zone"] in ("under", "shared") or m["name"] in ("canopy", "outer_walls"):
            c = route_clearance(m)
            msgs.append(f"UGV route clearance to {m['name']:<12s}: {c:.2f} m")
            assert c > 0.4, f"UGV route too close to {m['name']}"
    return msgs


# ---------------------------------------------------------------- layout.png
COLORS = {"roof": "#2a78d6", "under": "#eb6834", "shared": "#1baf7a", "marker": "#eda100"}
INK, INK2, GRID, SURFACE = "#2b2b2a", "#6b6a64", "#d9d8d2", "#fcfcfb"


def plot_layout(path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    from matplotlib.patches import Circle, Patch, Rectangle

    fig, ax = plt.subplots(figsize=(11, 11), dpi=130)
    fig.patch.set_facecolor(SURFACE)
    ax.set_facecolor(SURFACE)
    half = L.FLOOR_SIZE / 2

    floor = L.model_by_name("floor")
    for part in floor["parts"]:
        x0, x1, y0, y1, _, _ = part_extent(floor, part)
        ax.add_patch(Rectangle((x0, y0), x1 - x0, y1 - y0, fill=False, ec=GRID, lw=1))
        ax.text(x0 + 0.15, y0 + 0.15, part["name"].replace("tile_", "T"), fontsize=7, color=INK2)

    walls = L.model_by_name("outer_walls")
    for part in walls["parts"]:
        x0, x1, y0, y1, _, _ = part_extent(walls, part)
        ax.add_patch(Rectangle((x0, y0), x1 - x0, y1 - y0, fc="#8c8b85", ec="none"))

    canopy = L.model_by_name("canopy")
    for part in canopy["parts"]:
        x0, x1, y0, y1, z0, z1 = part_extent(canopy, part)
        if part["name"].startswith("pillar"):
            ax.add_patch(Rectangle((x0, y0), x1 - x0, y1 - y0, fc="#5f5e59", ec="none", zorder=4))
        elif part["name"] == "roof_body":
            ax.add_patch(Rectangle((x0, y0), x1 - x0, y1 - y0, fill=False, ec=INK, lw=1.6, ls=(0, (6, 4)), zorder=5))
            ax.text(x0 + 0.1, y1 + 0.15, f"Canopy roof {f(x1 - x0)} x {f(y1 - y0)} m, "
                    f"z {f(L.ROOF_BOTTOM_Z)}-{f(L.ROOF_TOP_Z)}", fontsize=9, color=INK)

    for m in L.MODELS:
        if m["zone"] not in COLORS:
            continue
        col = COLORS[m["zone"]]
        for part in m["parts"]:
            x0, x1, y0, y1, _, _ = part_extent(m, part)
            alpha = 0.35 if m["zone"] == "marker" else 0.85
            if part["shape"] == "cylinder":
                ax.add_patch(Circle(((x0 + x1) / 2, (y0 + y1) / 2), (x1 - x0) / 2, fc=col, ec=SURFACE, lw=2,
                                    alpha=alpha, zorder=6))
            else:
                ax.add_patch(Rectangle((x0, y0), x1 - x0, y1 - y0, fc=col, ec=SURFACE, lw=2, alpha=alpha, zorder=6))
        x0, x1, y0, y1, z0, z1 = model_extent(m)
        dims = (f"r{f(m['parts'][0]['size'][0])} h{f(m['parts'][0]['size'][1])}"
                if len(m["parts"]) == 1 and m["parts"][0]["shape"] == "cylinder"
                else f"{f(x1 - x0)}x{f(y1 - y0)}x{f(z1 - z0)}")
        cx, cy = m["pose"][0], m["pose"][1]
        txt = f"{m['label']}\n({f(cx)}, {f(cy)})  {dims}"
        if m["zone"] != "marker":
            txt += f"\nz {f(z0)}-{f(z1)}"
        below = cy < 0 and m["zone"] != "marker"
        ax.text(cx, (y0 - 0.2) if below else (y1 + 0.2), txt, ha="center", va="top" if below else "bottom",
                fontsize=8, color=INK, zorder=8,
                bbox=dict(boxstyle="round,pad=0.2", fc=SURFACE, ec="none", alpha=0.85))

    rx, ry = zip(*L.UGV_ROUTE)
    ax.plot(rx, ry, color=INK, lw=2, zorder=7)
    ax.plot(rx, ry, "o", color=INK, ms=4, zorder=7)
    for a, b in zip(L.UGV_ROUTE[:-1], L.UGV_ROUTE[1:]):
        ax.annotate("", xy=((a[0] + b[0]) / 2 + 0.01 * (b[0] - a[0]), (a[1] + b[1]) / 2 + 0.01 * (b[1] - a[1])),
                    xytext=((a[0] + b[0]) / 2, (a[1] + b[1]) / 2),
                    arrowprops=dict(arrowstyle="-|>", color=INK, lw=2), zorder=7)

    ax.set_xlim(-half - 0.6, half + 0.6)
    ax.set_ylim(-half - 0.6, half + 0.6)
    ax.set_aspect("equal")
    ax.set_xticks(np.arange(-10, 11, 2.5))
    ax.set_yticks(np.arange(-10, 11, 2.5))
    ax.tick_params(colors=INK2, labelsize=8)
    for s in ax.spines.values():
        s.set_color(GRID)
    ax.set_xlabel("x [m]", color=INK2)
    ax.set_ylabel("y [m]", color=INK2)
    ax.set_title(f"{L.WORLD_NAME} — top view (origin = map centre, z up). "
                 f"UAV altitude {f(L.DRONE_ALTITUDE)} m", color=INK, fontsize=12, loc="left")
    handles = [
        Patch(fc=COLORS["under"], label="Under roof (UGV only)"),
        Patch(fc=COLORS["roof"], label="On roof (UAV only)"),
        Patch(fc=COLORS["shared"], label="Shared landmark (both)"),
        Patch(fc=COLORS["marker"], alpha=0.35, label="Start / goal marker (no collision)"),
        Patch(fc="#5f5e59", label="Pillar 0.3x0.3x3"),
        Patch(fc="#8c8b85", label="Outer wall (h 3 m)"),
        Line2D([], [], color=INK, ls=(0, (6, 4)), lw=1.6, label="Canopy roof edge"),
        Line2D([], [], color=INK, lw=2, marker="o", ms=4, label="Recommended UGV route"),
    ]
    ax.legend(handles=handles, loc="upper center", bbox_to_anchor=(0.5, -0.07), ncol=4, frameon=False, fontsize=8,
              labelcolor=INK)
    fig.tight_layout()
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)


# ---------------------------------------------------------------- README table
def readme_table():
    rows = ["| Model (`model://`) | Description | Zone | Centre (x, y) [m] | Size [m] | z range [m] |",
            "|---|---|---|---|---|---|"]
    for m in L.MODELS:
        x0, x1, y0, y1, z0, z1 = model_extent(m)
        if m["name"] == "floor":
            size = f"{f(L.FLOOR_SIZE)} x {f(L.FLOOR_SIZE)}, 16 tiles of {f(L.FLOOR_TILE)} x {f(L.FLOOR_TILE)}"
            z0 = z1 = 0.0
        elif m["name"] == "outer_walls":
            size = f"walls at x, y = ±{f(L.WALL_HALF_EXTENT)}, h {f(L.WALL_HEIGHT)}, t {f(L.WALL_THICKNESS)}"
        elif m["name"] == "canopy":
            size = (f"roof {vec(*L.ROOF_SIZE).replace(' ', ' x ')}; pillars {vec(*L.PILLAR_SIZE).replace(' ', ' x ')} "
                    f"at x ∈ {{{', '.join(f(v) for v in L.PILLAR_XS)}}}, y = ±{f(abs(L.PILLAR_YS[0]))}")
        elif len(m["parts"]) == 1 and m["parts"][0]["shape"] == "cylinder":
            size = f"cylinder r {f(m['parts'][0]['size'][0])}, h {f(m['parts'][0]['size'][1])}"
        else:
            shape = {"lm_lshape": "L-block (arm 0.6)", "lm_stairs": "3 steps 0.6/1.2/1.8"}.get(m["name"], "box")
            size = f"{shape} {f(x1 - x0)} x {f(y1 - y0)} x {f(z1 - z0)}"
        rows.append(f"| `{m['name']}` | {m['label']} | {ZONE_TEXT[m['zone']]} | ({f(m['pose'][0])}, {f(m['pose'][1])}) "
                    f"| {size} | {f(z0)} – {f(z1)} |")
    return "\n".join(rows)


def update_readme():
    path = os.path.join(PKG_DIR, "README.md")
    if not os.path.exists(path):
        return False
    text = open(path, encoding="utf-8").read()
    if README_BEGIN not in text:
        return False
    head, rest = text.split(README_BEGIN, 1)
    _, tail = rest.split(README_END, 1)
    open(path, "w", encoding="utf-8").write(f"{head}{README_BEGIN}\n{readme_table()}\n{README_END}{tail}")
    return True


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-plot", action="store_true")
    args = ap.parse_args()
    for msg in checks():
        print("  check:", msg)
    for m in L.MODELS:
        d = os.path.join(PKG_DIR, "models", m["name"])
        os.makedirs(d, exist_ok=True)
        open(os.path.join(d, "model.sdf"), "w").write(model_sdf(m))
        open(os.path.join(d, "model.config"), "w").write(model_config(m))
        print(f"  models/{m['name']}/model.sdf")
    os.makedirs(os.path.join(PKG_DIR, "worlds"), exist_ok=True)
    open(os.path.join(PKG_DIR, "worlds", f"{L.WORLD_NAME}.sdf"), "w").write(world_sdf())
    print(f"  worlds/{L.WORLD_NAME}.sdf")
    if not args.no_plot:
        os.makedirs(os.path.join(PKG_DIR, "docs"), exist_ok=True)
        plot_layout(os.path.join(PKG_DIR, "docs", "layout.png"))
        print("  docs/layout.png")
    print("  README.md table", "updated" if update_readme() else "skipped (no markers)")


if __name__ == "__main__":
    main()
