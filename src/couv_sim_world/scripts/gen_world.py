"""Generate model.config / model.sdf for every model, worlds/canopy_world.sdf,
docs/layout.png and the coordinate table in README.md from scripts/layout.py.

Usage:
    python3 scripts/gen_world.py            # everything
    python3 scripts/gen_world.py --no-plot  # skip docs/layout.png
"""
import argparse
